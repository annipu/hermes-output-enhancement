// Package only the reviewed CSS as one plain ESM disk plugin. No model/prompt code.
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { version } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const candidate = await readFile(path.join(root, 'styles/p1-candidate.css'), 'utf8')
const scope = '[data-slot="aui_assistant-message-content"]'
if (!candidate.includes("[data-style-probe='candidate']")) throw new Error('Missing reviewed CSS scope')
const css = candidate
  .replace(/\/\*[^]*?\*\//g, '')
  .replaceAll("[data-style-probe='candidate']", scope)
  .trim()
const source = `// Hermes Style alpha: read-only transcript styling, loaded through the documented disk-plugin contract.
// Generated by scripts/build-plugin.mjs from styles/p1-candidate.css. Do not add prompt or message processing.
const CSS = ${JSON.stringify(css)}
const STYLE_ATTRIBUTE = 'data-hermes-style-plugin'
const ID = 'hermes-style-plugin'

export default {
  id: ID,
  name: 'Hermes Output Style Enhancement',
  description: 'Enhances how existing Markdown in assistant replies is displayed — headings, bold text, inline code and tables get theme-aware light/dark styling. Display only: reply content is never modified; no model calls, session reads or history writes. Off by default; toggle in Settings → Capabilities → Plugins.',
  defaultEnabled: false,
  register(ctx) {
    if (typeof ctx?.onDispose !== 'function') {
      throw new Error('Hermes Style requires the documented onDispose lifecycle API.')
    }
    if (document.head.querySelector('style[' + STYLE_ATTRIBUTE + '="' + ID + '"]')) {
      throw new Error('Hermes Style is already active; disable the previous instance before reloading.')
    }
    const style = document.createElement('style')
    style.setAttribute(STYLE_ATTRIBUTE, ID)
    style.textContent = CSS
    ctx.onDispose(() => style.remove())
    document.head.append(style)
  }
}
`
const out = path.join(root, 'plugin/hermes-style-plugin')
await mkdir(out, { recursive: true })
await writeFile(path.join(out, 'plugin.js'), source)
const info = {
  version, id: 'hermes-style-plugin', defaultEnabled: false,
  cssSourceSha256: createHash('sha256').update(candidate).digest('hex'),
  pluginSha256: createHash('sha256').update(source).digest('hex'),
  files: ['plugin.js', 'README.md', 'build-info.json'],
  scope: 'Read-only assistant-reply CSS; no SDK requests, prompt changes, message processing, or storage API.',
}
await writeFile(path.join(out, 'build-info.json'), JSON.stringify(info, null, 2) + '\n')
console.log(JSON.stringify(info))
